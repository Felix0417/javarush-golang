package main

/*
Вы пишете маленькую консольную утилиту для актёра озвучки: у него есть один any, в который по очереди кладут совершенно
разные вещи для записи — то номер дубля, то короткий код языка. Ваша задача — показать, что один и тот же any действительно
умеет хранить разные конкретные типы, и как это видно при печати.

Внутри main заведите переменную payload типа any. Сначала положите в неё целое число 42 и выведите в одной строке значение
и конкретный тип, который сейчас лежит внутри. Затем в тот же payload положите строку "go" и снова выведите значение и
конкретный тип в одной строке.

Формат каждой строки должен быть одинаковым: value=<значение> type=<тип>. Каждая запись выводится с новой строки.
*/

import "fmt"

func main() {
	// Один "чемодан" any, в который по очереди кладём значения разных конкретных типов.
	var payload any

	payload = 42
	// TODO: Выведите значение payload и его конкретный тип в формате value=<значение> type=<тип> (используйте %v и %T), затем перевод строки.
	fmt.Printf("value=%v type=%T\n", payload, payload)

	payload = "go"
	// TODO: Выведите значение payload и его конкретный тип в формате value=<значение> type=<тип> (используйте %v и %T), затем перевод строки.
	fmt.Printf("value=%v type=%T\n", payload, payload)
}
