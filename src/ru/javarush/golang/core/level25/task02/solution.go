package main

/*
Представьте, что вы собираете посылку: иногда коробка реально пустая (в any лежит “ничего”), а иногда внутри лежит “ярлык
на предмет”, но сам предмет — nil-указатель. Снаружи это выглядит похоже, и новичкам легко запутаться. Вы делаете
мини-демонстрацию, которая чётко покажет разницу.

В main объявите переменную box типа any без присваивания. Выведите строку empty=<результат>, где результат — это значение
сравнения (box == nil).

Далее объявите переменную counterPtr типа *int со значением nil, положите её в box (то есть сделайте box = counterPtr)
и выведите строку typedNil=<результат>, где результат — значение сравнения (box == nil).

В конце выведите строку type=<тип> value=<значение> для box, используя %T и %v.
*/

import "fmt"

func main() {
	var box any

	empty := box == nil
	// TODO: вычислите результат сравнения для "пустой коробки" (когда box не содержит ни типа, ни значения)
	fmt.Printf("empty=%v\n", empty)

	var counterPtr *int = nil
	// TODO: положите counterPtr в box (сохраните тип *int внутри интерфейса)
	box = counterPtr

	typedNil := box == nil
	// TODO: вычислите результат сравнения после помещения nil-указателя в интерфейс (typed nil)
	fmt.Printf("typedNil=%v\n", typedNil)

	fmt.Printf("type=%T value=%v\n", box, box)
}
