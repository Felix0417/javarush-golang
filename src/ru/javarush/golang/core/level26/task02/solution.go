package main

/*
Вы настраиваете простой мониторинг: в программу “льются” данные (например, лог или какой-то поток), а вам нужно понять,
сколько байтов реально прошло через io.Reader. Важно: поток может быть большим, поэтому читать “всё сразу” нельзя — только
кусочками через буфер.

Реализуйте функцию CountBytes(r io.Reader) (int, error), которая читает данные из r до конца и возвращает количество
реально прочитанных байт. Читайте в цикле через Read в буфер фиксированного размера (например, 32 байта) и учитывайте
только buf[:n] на каждом шаге.

В main() вызовите CountBytes(os.Stdin) и выведите итоговое число в stdout. Если при чтении случилась ошибка, отличная
от io.EOF, выведите текст ошибки в stderr.
*/

import (
	"fmt"
	"io"
	"os"
)

// CountBytes читает поток и возвращает число реально прочитанных байт.
//
// TODO: Реализуйте чтение до конца потока в цикле через r.Read в заранее выделенный буфер фиксированного размера.
// TODO: Суммируйте только фактически прочитанные байты (n), а не размер буфера.
// TODO: Обработайте io.EOF как штатное завершение (не возвращайте её наружу как ошибку).
// TODO: Учтите сценарий: Read вернул n > 0 и err != nil — эти n байт должны быть учтены, после чего верните ошибку (если это не io.EOF).
func CountBytes(r io.Reader) (int, error) {
	const bufSize = 32
	buf := make([]byte, bufSize)

	var sum int
	for {
		n, err := r.Read(buf[:bufSize])
		sum += n
		if err != nil && err != io.EOF {
			return sum, err
		} else if err == io.EOF {
			break
		}
	}
	return sum, nil
}

func main() {
	n, err := CountBytes(os.Stdin)
	if err != nil {
		// При ошибке (кроме EOF) печатаем только текст ошибки в stderr.
		fmt.Fprint(os.Stderr, err.Error())
		return
	}

	// В stdout выводим только итоговое число.
	fmt.Print(n)
}
