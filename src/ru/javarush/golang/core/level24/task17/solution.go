package main

/*
Вы пишете простую “карточку точки на карте” и хотите, чтобы она красиво печаталась в логах. Но заодно вам интересно
увидеть один из характерных моментов Go: один и тот же метод, объявленный на значении, подходит интерфейсу и для
значения T, и для указателя *T — и динамический тип в интерфейсе будет разный.

Напишите программу с типом Point (поля X и Y типа int) и методом String() string, объявленным с value receiver (receiver = Point).
Метод должен возвращать координаты в формате "(X,Y)" без пробелов.

В main создайте переменную p типа Point со значениями X=3, Y=4. Затем создайте две переменные интерфейсного типа fmt.Stringer:
одну присвойте значению p, вторую — указателю &p. Программа должна вывести по одной строке на каждую интерфейсную переменную:
динамический тип (%T) и строковое значение (%s).

Ожидаемый вывод:
a: main.Point (3,4)
b: *main.Point (3,4)
*/

import "fmt"

type Point struct {
	X int
	Y int
}

// String возвращает строковое представление точки.
func (p Point) String() string {
	// TODO: Реализуйте строковое представление точки в формате "(X,Y)" без пробелов.
	return fmt.Sprintf("(%d,%d)", p.X, p.Y)
}

func main() {
	// TODO: Создайте переменную p типа Point со значениями X=3 и Y=4.
	p := Point{X: 3, Y: 4}

	// TODO: Создайте две переменные типа fmt.Stringer:
	// TODO: - первая должна хранить значение p
	// TODO: - вторая должна хранить указатель &p
	var a fmt.Stringer = p
	var b fmt.Stringer = &p

	// TODO: Выведите ровно две строки в правильном порядке и формате:
	// TODO: a: <динамический тип> <строковое значение>
	// TODO: b: <динамический тип> <строковое значение>
	fmt.Printf("a: %T %s\n", a, a)
	fmt.Printf("b: %T %s\n", b, b)
}
