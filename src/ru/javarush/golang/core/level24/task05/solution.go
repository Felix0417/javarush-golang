package main

/*
Вы пишете систему, где "приветливый сотрудник" может быть подставлен в разные места программы. Но сначала сотрудника ещё
нет — он не нанят. Вам важно увидеть, как ведёт себя интерфейсная переменная, когда в ней действительно ничего нет, и как
всё меняется после присваивания конкретной реализации.

В коде вы объявляете интерфейс Greeter с методом Greet() string. В main создаёте переменную var g Greeter без присваивания
и печатаете: правда ли, что g == nil, и какой у g динамический тип через fmt.Printf с "%T". Затем объявляете структуру
(например, Robot) с методом Greet, присваиваете её значение в g и печатаете те же две диагностики снова. В конце
вызываете g.Greet() и печатаете строку приветствия, чтобы убедиться, что всё работает.
*/

import "fmt"

// Greeter — контракт: умеет возвращать строку приветствия.
type Greeter interface {
	Greet() string
}

type Robot struct{}

// Greet реализует интерфейс Greeter.
func (Robot) Greet() string {
	// TODO: Верните строку приветствия (любую осмысленную строку).
	return "Hello from Robot struct"
}

func main() {
	// Интерфейсная переменная без присваивания:
	// внутри неё нет ни динамического типа, ни значения.
	var g Greeter

	// TODO: Выведите до присваивания:
	// TODO: 1) результат сравнения (g == nil)
	// TODO: 2) динамический тип g через fmt.Printf("%T\n", g)
	fmt.Println(g == nil)
	fmt.Printf("%T\n", g)

	// TODO: Объявите конкретную структуру (Robot уже объявлен) и присвойте её значение в g.
	var r Robot
	g = r

	// TODO: Выведите после присваивания:
	// TODO: 1) результат сравнения (g == nil)
	// TODO: 2) динамический тип g через fmt.Printf("%T\n", g)
	fmt.Println(g == nil)
	fmt.Printf("%T\n", g)

	// TODO: Вызовите g.Greet() и напечатайте возвращаемую строку приветствия.
	fmt.Println(g.Greet())
}
